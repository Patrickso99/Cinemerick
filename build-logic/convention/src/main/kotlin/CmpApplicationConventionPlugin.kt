import com.preichert.cinemerick.convention.AppInfo
import com.preichert.cinemerick.convention.BASE_PACKAGE
import com.preichert.cinemerick.convention.apply
import com.preichert.cinemerick.convention.configureAndroidTarget
import com.preichert.cinemerick.convention.configureDesktopTarget
import com.preichert.cinemerick.convention.configureIosTargets
import com.preichert.cinemerick.convention.libs
import com.preichert.cinemerick.convention.pathToPackageName
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.api.plugins.ExtensionAware
import org.gradle.kotlin.dsl.configure
import org.gradle.kotlin.dsl.getByType
import org.jetbrains.kotlin.gradle.dsl.KotlinMultiplatformExtension
import org.jetbrains.compose.ComposeExtension
import org.jetbrains.compose.desktop.application.dsl.TargetFormat
import org.jetbrains.compose.desktop.DesktopExtension

class CmpApplicationConventionPlugin : Plugin<Project> {

    override fun apply(target: Project) {
        with(target) {
            with(pluginManager) {
                apply(libs.plugins.android.kotlin.multiplatform.library)
                apply(libs.plugins.kotlin.multiplatform)
                apply(libs.plugins.compose.multiplatform)
                apply(libs.plugins.kotlin.compose)
            }

            configureAndroidTarget(pathToPackageName())
            configureDesktopTarget()
            configureIosTargets(frameworkName = "ComposeApp")

            val composeDependencies = extensions.getByType<ComposeExtension>().dependencies
            extensions.configure<KotlinMultiplatformExtension> {
                sourceSets.getByName("desktopMain").dependencies {
                    implementation(composeDependencies.desktop.currentOs)
                    implementation(libs.compose.ui.tooling)
                }
                sourceSets.named("androidMain") {
                    dependencies {
                        implementation(libs.compose.ui.tooling)
                    }
                }
            }

            extensions.configure<ComposeExtension> {
                (this as ExtensionAware).extensions.configure<DesktopExtension>("desktop") {
                    application {
                        mainClass = "$BASE_PACKAGE.MainKt"
                        nativeDistributions {
                            targetFormats(TargetFormat.Dmg, TargetFormat.Msi, TargetFormat.Exe, TargetFormat.Deb)
                            packageName = AppInfo.NAME
                            packageVersion = AppInfo.VERSION_NAME
                            val iconsDir = file("src/desktopMain/resources")
                            macOS { iconFile.set(iconsDir.resolve("icon.icns")) }
                            windows { iconFile.set(iconsDir.resolve("icon.ico")) }
                            linux { iconFile.set(iconsDir.resolve("icon.png")) }
                        }
                    }
                }
            }

            registerIosVersionConfig()
        }
    }

    /**
     * Generates the xcconfig file with the app name, version and code. Referenced in iosApp/project.yml, which runs
     * `:app:generateIosVersionConfig` before building the framework.
     */
    private fun Project.registerIosVersionConfig() {
        val iosConfigFile = rootProject.file("iosApp/Config.xcconfig")
        val iosConfigContent = """
            // Generated by Gradle - do not edit manually
            APP_NAME = ${AppInfo.NAME}
            MARKETING_VERSION = ${AppInfo.VERSION_NAME}
            CURRENT_PROJECT_VERSION = ${AppInfo.VERSION_CODE}
        """.trimIndent()

        tasks.register("generateIosVersionConfig") {
            inputs.property("content", iosConfigContent)
            outputs.file(iosConfigFile)
            doLast {
                iosConfigFile.writeText(iosConfigContent)
                println("Generated $iosConfigFile")
            }
        }
    }
}
