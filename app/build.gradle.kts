/**
 * Generate xcconfig file for iOS with app name, version and code.
 * Referenced in iosApp/project.yml configFiles.
 */
val iosConfigFile = rootProject.file("iosApp/Config.xcconfig")
val iosConfigContent = """
    // Generated by Gradle - do not edit manually
    APP_NAME = ${AppInfo.NAME}
    MARKETING_VERSION = ${AppInfo.VERSION_NAME}
    CURRENT_PROJECT_VERSION = ${AppInfo.VERSION_CODE}
""".trimIndent()

tasks.register("generateIosVersionConfig") {
    inputs.property("content", iosConfigContent)
    outputs.file(iosConfigFile)
    doLast {
        iosConfigFile.writeText(iosConfigContent)
        println("Generated $iosConfigFile")
    }
}

